def _pos(x, y, h):
    return (float(x), float(y), float(h))


# ---------------------------------------------------------------- 등속 질주 경로
# ★lv1a 골목의 원근 (내가 프레임에서 잰 값)
#     발밑 y 와 화면키 h 는 **1차 관계**다(지평선 위로 h 에 비례).  y = 167.7 + 11.214·h
#     골목 중심선                                                   x = 658 - 0.19·(y-400)
#   렌즈 초점거리는 가로 1280 · 수평화각 60도로 보아 F ≈ 1108px.
#   카메라까지 거리(키 단위) = F / h  →  **이 값이 시간에 비례해야 등속**이다.
_F, _YH, _K = 1108.0, 167.7, 11.214


def _x_on_lane(y):
    return 658.0 - 0.19 * (y - 400.0)


def run_keys(h0, h1, n=14):
    """전력질주 구간의 열쇠점 — **땅 위를 등속으로** 나아가게 만든다.

    ★왜 이렇게 하나 (2026-08-23 실측)
      두 점만 주고 맡기면 렌더러가 smoothstep 으로 이어서 **양끝은 제자리걸음,
      한가운데는 활강**이 된다. 실측 한 스트라이드당 0.14키 → 4.4키 → 0.14키.
      사람이 전력질주하면 한 스트라이드(0.5초)에 **2.2~2.6키**를 나아간다.
      깊이(F/h)를 시간에 정비례로 깔고 `ease="linear"` 로 이으면 내내 그 값이 나온다.
    """
    d0, d1 = _F / h0, _F / h1
    out = []
    for i in range(n + 1):
        p = i / float(n)
        h = _F / (d0 + (d1 - d0) * p)
        y = _YH + _K * h
        out.append((round(p, 4), round(_x_on_lane(y), 1), round(y, 1), round(h, 2)))
    return out


