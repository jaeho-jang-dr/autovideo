# ---------------------------------------------------------------- 이동컷 방향표
# ★왼쪽 이동컷은 실파일 반전으로 이미 만들어져 있고 DB flip=0 이다(이중 반전 사고 방지).
GO_R = {"walk_r", "run_r", "walk_diag_in_r", "run_diag_in_r"}
GO_L = {"walk_l", "run_l", "walk_diag_in_l", "run_diag_in_l",
        "walk_diag_out_l", "run_diag_out_l"}
TO_CAM = {"walk_front", "run_front"}            # 카메라 쪽으로 온다 → 커진다
AWAY = {"walk_back", "run_back"}                # 멀어진다 → 작아진다
DIAG_IN = {"walk_diag_in_r", "run_diag_in_r", "walk_diag_in_l", "run_diag_in_l"}
DIAG_OUT = {"walk_diag_out_l", "run_diag_out_l"}

ENTER_SEC = {"walk": 1.45, "run": 1.15}
EXIT_SEC = 1.05


def enter_start(cut, pos):
    """이동컷의 **시작** 발밑·키 — 어디에서 들어오는가."""
    x, y, h = pos
    if cut in GO_R:
        sx = -150.0
    elif cut in GO_L:
        sx = 1430.0
    else:
        sx = x
    if cut in TO_CAM:                            # 안쪽에서 카메라 쪽으로
        return (sx, y - 95.0, h * 0.70)
    if cut in AWAY:                              # 카메라 앞에서 안쪽으로
        return (sx, y + 78.0, h * 1.20)
    if cut in DIAG_IN:                           # 뒤에서 앞으로 비스듬히
        return (sx, y - 72.0, h * 0.80)
    if cut in DIAG_OUT:                          # 앞에서 안쪽으로 비스듬히
        return (sx, y + 66.0, h * 1.17)
    return (sx, y, h)


def exit_end(cut, pos):
    """나가는 이동컷의 **끝** 발밑·키."""
    x, y, h = pos
    tx = -150.0 if cut in GO_L else 1430.0
    if cut in DIAG_OUT:
        return (tx, y - 60.0, h * 0.82)
    return (tx, y, h)
