def foot_of(h):
    ks = sorted(FOOT)
    for i in range(len(ks) - 1):
        if h <= ks[i + 1]:
            a, b = ks[i], ks[i + 1]
            u = (h - a) / float(b - a)
            return int(FOOT[a] + (FOOT[b] - FOOT[a]) * u)
    return FOOT[ks[-1]]


