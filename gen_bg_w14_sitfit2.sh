#!/bin/bash
# ★W14 앉기 배경 재작업 v2 — v1 실패 원인: "사람 자리를 비워라"를 agy가 "배경을 비워라"로 오해해 백지 생성.
#   v2 수정: ①배경은 반드시 충실하게 꽉 채워 그린다(디테일 풍부) ②단, 지정 사각형 영역에만 '가구'를 놓지 않는다
#   ★캐릭터 최우선 원칙: 캐릭터 크기·위치는 고정(앉기=서기 60%), 배경이 사람에 맞춘다.
cd /d/Entertainments/DevEnvironment/autovideo
export PATH="$PATH:/c/Users/antigravity/AppData/Local/agy/bin"
OUT='D:\Entertainments\DevEnvironment\autovideo\assets\graphics\bg'
LOG="logs/gen_bg_w14_sitfit2.log"
mkdir -p logs; : > "$LOG"

# ★핵심: 배경은 풍성하게. '비우기'는 오직 가구 배치 제약일 뿐.
RULE="⚠️구도 규칙(반드시 지켜라): 이 그림 위에 '의자에 앉은 여성 캐릭터'가 나중에 합성된다. 그 사람은 화면 왼쪽-중앙(가로 27~46% 지점, 세로 61~97% 지점)에 앉고, 그 캐릭터 그림에는 **의자와 책상 앞부분이 이미 포함**되어 있다.
 → 따라서 그 구역(왼쪽-중앙 하단)에는 **의자나 테이블 같은 큰 가구를 놓지 마라**(사람과 겹친다). 그 구역은 바닥/카펫/러그 등 평평한 면으로 두어라.
 → 대신 **배경 자체는 절대 비워두지 말고 아주 충실하고 풍성하게 그려라**: 벽·창문·조명·가구·소품·식물·창밖 풍경을 꽉 채워 완성도 높게. 텅 빈 흰 벽이나 백지 같은 화면은 절대 금지.
 → 큰 가구(책상·식탁·카운터·소파)는 화면 **오른쪽 절반(가로 50~100%)** 에 배치하고, 상판 높이는 화면 세로 81% 지점, 바닥은 세로 97% 지점에 맞춘다. 사람이 그 옆에 앉으면 눈높이가 자연스럽게 이어지도록."

COMMON="가로 16:9 (1280x720). 플랫 카툰 일러스트, 굵은 검정 외곽선, 부드러운 파스텔 색감, 따뜻하고 아늑한 분위기. ⚠️화면에 어떤 글자·숫자·상표·간판 텍스트도 절대 넣지 마라(표지판·시계 문자판은 빈칸). 사람은 배경에 아주 작은 실루엣으로만."

declare -A P
P[bg_w14_desk_fit]="한낮의 공부방. 오른쪽에 넓은 나무 책상(위에 책·노트·스탠드·연필꽂이), 벽에 가득한 책꽂이, 화분, 커다란 창으로 들어오는 밝은 햇살, 창밖에 에메랄드 바다와 야자수. 바닥엔 러그."
P[bg_w14_cafe_fit]="아늑한 해변 카페 내부. 오른쪽에 나무 테이블과 커피잔·노트북 자리, 벽에 선반과 커피 도구·화분·매달린 조명, 큰 창밖으로 에메랄드 바다와 야자수, 따뜻한 나무 인테리어."
P[bg_w14_kitchen2]="아침 주방 카운터 코너. 오른쪽에 주방 카운터(커피포트·머그컵·과일 바구니·빵), 벽 선반에 그릇과 향신료 병, 창밖으로 바다, 아침 햇살이 쏟아짐. 왼쪽 벽엔 시계(문자판 빈칸)와 액자."
P[bg_w14_beachtable_fit]="해변 야외 테라스 카페. 오른쪽에 나무 테이블과 파라솔, 화분과 매달린 전구 장식, 난간 너머로 흰 백사장·에메랄드 바다·작은 섬(비양도)·야자수. 한낮의 밝은 빛."
P[bg_w14_dinner]="저녁 시간 해변 식당 실내. 오른쪽에 긴 나무 식탁(접시·컵·촛불), 천장에 따뜻한 펜던트 조명 여러 개, 벽엔 선반과 화분·액자, 큰 창밖은 주황빛 노을 지는 바다. 아늑하고 꽉 찬 실내."
P[bg_w14_nightdesk_fit]="밤의 아늑한 방. 오른쪽에 나무 책상(스탠드 불빛·펼친 일기장·머그컵·작은 화분), 벽에 책꽂이와 액자·시계(문자판 빈칸), 커튼 달린 창밖엔 별이 가득한 밤하늘과 어두운 바다. 바닥엔 러그. 따뜻한 노란 조명."

echo "=== v2 시작 $(date) ===" >> "$LOG"
MAX=3; i=0
for k in "${!P[@]}"; do
  echo "[gen] $k" >> "$LOG"
  agy -p "${P[$k]} ${RULE} ${COMMON} 결과 PNG를 '${OUT}\\${k}.png' 로 저장하라." --dangerously-skip-permissions < /dev/null >> "$LOG" 2>&1 &
  i=$((i+1)); if (( i % MAX == 0 )); then wait; fi
done
wait
echo "=== done $(date) ===" >> "$LOG"
for k in "${!P[@]}"; do
  f="assets/graphics/bg/${k}.png"
  [ -f "$f" ] && echo "✅ $k $(stat -c%s "$f")" || echo "★실패 $k"
done
